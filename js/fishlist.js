// Fix up a few placeholder ids so they read sensibly in saved data.
const FIX = { 'crevalle-other': 'atlantic-bumper', 'tripletail-other': 'atlantic-needlefish', 'red-lionfish': 'squirrelfish', 'cobia-other': 'atlantic-cutlassfish', 'gray-snapper-juv': 'sheepshead-minnow', 'tarpon-ten': 'atlantic-tenpounder', 'cobia-remora': 'sharksucker', 'sheepshead-porgy': 'sea-bream', 'red-grouper-juv': 'gag-juvenile', 'frigate': 'tripletail-juvenile' };
const SKIP = new Set(['snook-other', 'tripletail-juvenile', 'gag-juvenile']);

export const FISH = RAW.map(([id, name, aka, group]) => ({ id: FIX[id] || id, name, aka: aka ? aka.split(',').map(s => s.trim()).filter(Boolean) : [], group }))
  .filter(f => !SKIP.has(f.id));

export const fishById = id => FISH.find(f => f.id === id) || null;
